def bundler_version(lock):
    match = re.search(r"(?m)^BUNDLED WITH\n\s+(\d+\.\d+\.\d+)\s*$", lock)
    if not match:
        raise ContractError("frozen Gemfile.lock has no exact Bundler version")
    if re.search(r"(?m)^GIT\n", lock):
        raise ContractError("Bundler Git source needs a pinned-history-free export adapter")
    for path in re.findall(r"(?ms)^PATH\n(.*?)(?=^\S|\Z)", lock):
        if not re.search(r"(?m)^  remote: \.\s*$", path):
            raise ContractError("Bundler external path source needs a candidate-source link adapter")
    return match[1]


def install_command(plan, lock_text):
    if plan["kind"] == "composer":
        commands = [
            composer_policy_command(plan, "/tmp/composer"),
            composer_alias_command(plan, "/workspace", "/tmp/composer-alias", create=False),
            shlex.join(["composer", "install", *plan["install_flags"]]),
            composer_alias_command(plan, "/workspace", "/tmp/composer-alias", create=True),
        ]
        return " && ".join(command for command in commands if command)
    version = bundler_version(lock_text)
    bootstrap = DEPENDENCY_CACHE + "/bootstrap"
    return ("gem install bundler --version " + version + " --no-document --install-dir " + bootstrap +
            " && " + bootstrap + "/bin/bundle _" + version + "_ install --jobs 2 --retry 1")


def composer_payload(source, payload, tracked, workspace="."):
    """Preserve tracked source; only new vendor paths can become build scratch."""
    vendor = source / "vendor"
    if not vendor.is_dir():
        raise ContractError("Composer did not produce its default vendor directory")
    prefix = (workspace + "/" if workspace != "." else "") + "vendor/"
    for name, path in tree_files(vendor).items():
        original = tracked.get(prefix + name)
        if original is not None:
            if path.is_symlink() or path.read_bytes() != original:
                raise ContractError("Composer install changed a tracked vendor source: " + prefix + name)
            continue
        target = payload / "vendor" / name
        target.parent.mkdir(parents=True, exist_ok=True)
        if path.is_symlink():
            if not path.resolve().is_relative_to(vendor.resolve()):
                raise ContractError("Composer dependency link escapes vendor")
            target.symlink_to(os.readlink(path))
        else:
            shutil.copy2(path, target)
    top = sorted(path.name for path in (payload / "vendor").iterdir())
    scratch = []
    for name in top:
        relative = prefix + name
        if any(path == relative or path.startswith(relative + "/") for path in tracked):
            raise ContractError("prepared vendor directory overlaps tracked candidate source: " + relative)
        scratch.append(relative)
    return scratch


def validate_install_inputs(cwd, plan, inputs, *, installed=False):
    """Only an explicitly absent start lock may be generated by installation."""
    if plan["kind"] == "composer":
        config = json.loads(inputs["manifest"]).get("config", {})
        if (not isinstance(config, dict) or config.get("lock", True) is not True
                or config.get("vendor-dir", "vendor") != "vendor"):
            raise ContractError("bounded Composer install requires lock usage and the default vendor directory")
    for field, original in inputs.items():
        path = cwd / plan[field]
        if original is None and not installed:
            if path.exists() or path.is_symlink():
                raise ContractError("unlocked Composer install has a substituted start lock")
            continue
        if path.is_symlink() or not path.is_file():
            raise ContractError("dependency install needs a regular " + field)
        if original is not None and path.read_bytes() != original:
            raise ContractError("dependency install changed the frozen " + field)


def capture_composer_resolution(cwd, payload, plan, record):
    """Package new resolution evidence without claiming a historical lock."""
    lock = cwd / plan["lock"]
    if lock.is_symlink() or not lock.is_file():
        raise ContractError("unlocked Composer install did not produce a regular lock")
    data = json.loads(lock.read_bytes())
    if not isinstance(data, dict) or not isinstance(data.get("packages"), list):
        raise ContractError("unlocked Composer install did not produce a package lock")
    resolution = payload / "resolution"
    version = (resolution / "resolver-version.txt").read_text().strip()
    checksum = (resolution / "resolver-sha256.txt").read_text().strip().split(maxsplit=1)
    if not version or len(checksum) != 2 or not re.fullmatch(r"[0-9a-f]{64}", checksum[0]):
        raise ContractError("unlocked Composer install lacks actual resolver evidence")
    record.update(lock_origin=RESOLVED_COMPOSER_LOCK, lock_sha256=file_hash(lock),
                  resolver={"version": version, "sha256": checksum[0], "path": checksum[1].strip()})
    (resolution / "composer.lock").write_bytes(lock.read_bytes())
    provenance = {
        "kind": RESOLVED_COMPOSER_LOCK, "historical_lock": False, "start_lock_present": False,
        "id": record["id"], "repo": record["repo"], "start_sha": record["start_sha"],
        "workspace": plan["workspace"], "manifest_sha256": record["manifest_sha256"],
        "lock_sha256": record["lock_sha256"], "config_fingerprint": record["config_fingerprint"],
        "plan_sha256": canonical_hash(plan), "image": record["image"], "resolver": record["resolver"],
        "source_git_tree": record["source_git_tree"], "source_tree_sha256": record["source_tree_sha256"],
        "environment_sha256": record["environment_sha256"],
        "command_sha256": hashlib.sha256(record["command"].encode()).hexdigest(),
    }
    atomic_json(resolution / "provenance.json", provenance)
    archive = payload / "resolution.tar"
    with tarfile.open(archive, "w") as stream:
        for name in ("composer.lock", "provenance.json"):
            content = (resolution / name).read_bytes()
            entry = tarfile.TarInfo(name)
            entry.size, entry.mode = len(content), 0o644
            stream.addfile(entry, io.BytesIO(content))
    record.update(resolution_provenance_sha256=file_hash(resolution / "provenance.json"),
                  resolution_archive_sha256=file_hash(archive))


def reuse_prepared_dependencies(target, repository, task, case, plan):
    """A prepared or partially published payload is never silently re-resolved."""
    manifest = target / "preparation.json"
    old = json.loads(manifest.read_text()) if manifest.is_file() else None
    if old is not None and old.get("status") == "prepared":
        validate_prepared_dependencies(repository, task, case, plan, old, target / "payload")
        return old
    if (target / "payload").exists():
        raise ContractError("published scripted payload needs validation, not a new resolution")
    return None


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, required=True)
    parser.add_argument("--legacy-root", type=Path, required=True)
    parser.add_argument("--out-dir", type=Path, required=True)
    parser.add_argument("--task-ids", type=Path, required=True)
    parser.add_argument("--workers", type=int, default=2)
    parser.add_argument("--timeout-seconds", type=int, default=1200)
    parser.add_argument("--resolve-unlocked", action="store_true",
                        help="explicitly resolve allowlisted lockless Composer starts once")
    parser.add_argument("--toolchains", type=Path, help="shared pinned developer toolchain registry")
    args = parser.parse_args()
    config = load_config(args.config)
    if args.toolchains:
        config["migration"] = {**config.get("migration", {}),
                               "toolchain_registry": str(args.toolchains.resolve())}
    tasks = selected_tasks(Path(config["tasks"]), Path(config["scope_ids"]) if config.get("scope_ids") else None)
    oracles = read_jsonl(Path(config["oracles"]))
    batch = set(args.task_ids.read_text().splitlines())
    if not batch or not batch <= tasks.keys() or args.timeout_seconds < 1:
        raise ContractError("scripted preparation needs valid batch IDs and positive time bounds")
    cases = json.loads((args.legacy_root / "scripted/oracle_config.json").read_text())["tasks"]
    services = ExecutionServices(config)
    output = args.out_dir.resolve()
    with output_lock(output):
        ctx = MigrationContext(config, tasks, oracles, args.legacy_root.resolve(), output / "toolchains")

        def prepare(ident):
            task, oracle = tasks[ident], oracles[ident]
            target = output / component(ident)
            target.mkdir(exist_ok=True)
            record_file = target / "preparation.json"
            record = {"id": ident, "repo": task["repo"], "start_sha": task["start_sha"], "status": "preparing",
                      "expected_tasks": len(tasks), "model_calls": 0, "scoring_result": False}
            try:
                case = cases[str(oracle["index"])]
                plan = dependency_plan(case)
                if plan is None:
                    raise ContractError("this task needs no external dependency preparation")
                repository = ctx.repo(task)
                # Keep the published record untouched even when validation
                # rejects it. A retry may report a mismatch, never float again.
                try:
                    old = reuse_prepared_dependencies(target, repository, task, case, plan)
                except Exception as exc:
                    return {**record, "status": "pending", "error": f"{type(exc).__name__}: {exc}"}
                if old is not None:
                    return old
                retain_preparation_attempt(target)
                image_name = case.get("environment", {}).get("docker", "")
                if not (image_name.startswith("ruby:") or image_name.startswith("rb-scripted-php")):
                    raise ContractError("scripted dependency runtime is not a pinned Ruby/PHP image")
                prefix = plan["workspace"] + "/" if plan["workspace"] != "." else ""
                inputs = dependency_start_inputs(repository, task, plan, resolve_unlocked=args.resolve_unlocked)
                if plan["kind"] == "composer":
                    composer_home_config(plan, json.loads(inputs["manifest"]))
                candidate_mirror = composer_candidate.applies_to(task, plan)
                command = (composer_candidate.locked_install_command() if candidate_mirror else
                           install_command(plan, (inputs["lock"] or b"").decode()))
                if inputs["lock"] is None:
                    evidence = DEPENDENCY_CACHE + "/resolution"
                    command = (
                        "mkdir -p " + evidence +
                        " && composer --no-plugins --no-scripts --no-interaction --version --no-ansi > " +
                        evidence + "/resolver-version.txt" +
                        ' && sha256sum "$(command -v composer)" > ' + evidence + "/resolver-sha256.txt && " + command)
                record.update(plan=plan, config_fingerprint=canonical_hash(case),
                              lock_origin=RESOLVED_COMPOSER_LOCK if inputs["lock"] is None else "tracked-start-lock",
                              source_git_tree=git(repository, "rev-parse", task["start_sha"] + "^{tree}").decode().strip(),
                              **{key + "_sha256": hashlib.sha256(value).hexdigest()
                                 for key, value in inputs.items() if value is not None})
                size = services.source_bytes(task, repository)
                request = ResourceRequest("scripted-prepare:" + ident, cpus=2, memory_bytes=4 * GiB,
                                          scratch_bytes=size * 2 + 8 * GiB, heavy=size > GiB)
                with services.gate.acquire(request, uses_containers=True) as lease:
                    image, audit = ctx.image(image_name)
                    record.update(image=image, image_audit=audit)
                    with tempfile.TemporaryDirectory(prefix="scripted-dependencies-", dir=services.scratch) as temporary:
                        root = Path(temporary)
                        source, payload = root / "source", root / "payload"
                        # Dependency installation only needs root checkout
                        # files; runtime verification separately closes or
                        # explicitly omits each fixed gitlink.
                        if candidate_mirror:
                            composer_candidate.stage_locked_install(source, inputs["manifest"], inputs["lock"])
                            record["installation_input_kind"] = "manifest-only"
                            record["installation_input_tree_sha256"] = dependency_tree_fingerprint(source)
                        else:
                            with start_archive(repository, task["start_sha"]) as stream:
                                extract_tar(stream, source)
                            record["source_tree_sha256"] = dependency_tree_fingerprint(source)
                            initialize_git(source)
                        payload.mkdir()
                        cwd = source / plan["workspace"]
                        validate_install_inputs(cwd, plan, inputs)
                        container = "rb-scripted-prepare-" + uuid.uuid4().hex[:16]
                        argv = [
                            "docker", "run", "--rm", "--name", container, "--init", "--read-only",
                            "--network", "bridge", "--user", f"{os.getuid()}:{os.getgid()}",
                            "--cpus", "2", "--cpuset-cpus", bounded_cpu_set(2, lease["lease"]),
                            "--memory", "4096m", "--pids-limit", "256",
                            "--cap-drop=ALL", "--security-opt=no-new-privileges",
                            "--label", "reviewbench.resource-lease=" + lease["lease"],
                            "--tmpfs", "/tmp:rw,exec,nosuid,nodev,size=512m",
                            "--mount", f"type=bind,source={source},target=/workspace",
                            "--mount", f"type=bind,source={payload},target={DEPENDENCY_CACHE}",
                            "-w", "/workspace" + ("/" + plan["workspace"] if plan["workspace"] != "." else ""),
                        ]
                        env = {
                            "HOME": "/tmp", "CI": "true", "MAKEFLAGS": "-j2", "CMAKE_BUILD_PARALLEL_LEVEL": "2",
                            "COMPOSER_HOME": "/tmp/composer", "COMPOSER_MAX_PARALLEL_HTTP": "2",
                            "COMPOSER_MAX_PARALLEL_PROCESSES": "2", "COMPOSER_CACHE_DIR": "/composer-cache",
                            "COMPOSER_CACHE_READ_ONLY": "1", "BUNDLE_USER_CACHE": "/tmp/bundler",
                            **bundler_environment("/tmp/bundle-config"),
                        }
                        if plan.get("root_version"):
                            env["COMPOSER_ROOT_VERSION"] = plan["root_version"]
                        if plan["kind"] == "composer":
                            cache = args.legacy_root.resolve() / "scripted/cache/composer"
                            argv += ["--mount", f"type=bind,source={cache},target=/composer-cache,readonly"]
                        for key, value in sorted(env.items()):
                            argv += ["-e", key + "=" + value]
                        argv += ["--entrypoint", "/bin/bash", image, "-c", command]
                        record.update(command=shlex.join(argv), log=str(target / "install.log"),
                                      environment_sha256=canonical_hash(env))
                        atomic_json(record_file, record)
                        started = time.monotonic()
                        with (target / "install.log").open("w") as log:
                            process = subprocess.Popen(argv, stdout=log, stderr=subprocess.STDOUT)
                            try:
                                while process.poll() is None:
                                    if time.monotonic() - started > args.timeout_seconds:
                                        raise ContractError("scripted dependency preparation exceeded its time bound")
                                    if shutil.disk_usage(services.scratch).free < 80 * GiB:
                                        raise ContractError("scripted preparation reached the 80-GiB disk floor")
                                    time.sleep(.5)
                            finally:
                                if process.poll() is None:
                                    subprocess.run(["docker", "stop", "-t", "5", container],
                                                   capture_output=True, timeout=20)
                                    process.wait(timeout=30)
                        record.update(exit_status=process.returncode, seconds=round(time.monotonic() - started, 2),
                                      log_sha256=file_hash(target / "install.log"))
                        if process.returncode:
                            raise ContractError("frozen scripted dependency install failed")
                        validate_install_inputs(cwd, plan, inputs, installed=True)
                        if inputs["lock"] is None:
                            capture_composer_resolution(cwd, payload, plan, record)
                        record["scratch_paths"] = []
                        if candidate_mirror:
                            tracked = [name.decode() for name in git(
                                repository, "ls-tree", "-r", "--name-only", "-z", task["start_sha"]
                            ).split(b"\0") if name]
                            candidate_payload = payload / "composer-current"
                            composer_candidate.export_dependency_payload(
                                cwd, candidate_payload, tracked,
                                manifest=inputs["manifest"], lock=inputs["lock"])
                            payload_bytes = sum(path.stat().st_size for path in tree_files(candidate_payload).values()
                                                if not path.is_symlink())
                            record["composer_candidate"] = {
                                "schema": composer_candidate.SCHEMA, "path": "composer-current",
                                "record_sha256": file_hash(candidate_payload / composer_candidate.RECORD),
                                "extra_scratch_mb": (size + payload_bytes + 1024 ** 2 - 1) // 1024 ** 2,
                            }
                        elif plan["kind"] == "composer":
                            aliases = composer_alias_paths(plan)
                            tracked_names = git(repository, "ls-tree", "-r", "--name-only", "-z",
                                                task["start_sha"], "--", prefix + "vendor", *aliases).split(b"\0")
                            tracked = {name.decode(): git(repository, "show", task["start_sha"] + ":" + name.decode())
                                       for name in tracked_names if name}
                            if any(name == alias or name.startswith(alias + "/") for name in tracked for alias in aliases):
                                raise ContractError("Composer vendor alias overlaps tracked candidate source")
                            record["scratch_paths"] = composer_payload(cwd, payload, tracked, plan["workspace"])
                            record["scratch_paths"].extend(aliases)
                        destination = target / "payload"
                        if destination.exists():
                            raise ContractError("existing scripted payload needs a new preparation directory")
                        shutil.copytree(payload, destination, symlinks=True)
                        record.update(status="prepared", payload_tree_sha256=dependency_tree_fingerprint(destination))
            except Exception as exc:
                record.update(status="pending", error=f"{type(exc).__name__}: {exc}")
            atomic_json(record_file, record)
            return record

        records = {}
        for ident, record in completed_jobs(prepare, sorted(batch), args.workers):
            records[ident] = record
            print(json.dumps({key: record.get(key) for key in ("id", "status", "exit_status", "error")}), flush=True)
            atomic_json(output / "preparation-summary.json", {
                "expected_tasks": len(tasks), "batch_tasks": len(batch),
                "prepared": sum(row["status"] == "prepared" for row in records.values()), "records": records,
            })
        atomic_json(output / "resource-usage.json", services.gate.status())
    return 0 if records and all(row["status"] == "prepared" for row in records.values()) else 2


if __name__ == "__main__":
    raise SystemExit(main())
